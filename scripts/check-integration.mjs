import {chromium, expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1280,height:800}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.route('https://play.pokemonshowdown.com/**',r=>r.fulfill({contentType:'text/html',body:'<!doctype html><html><body><button name="chooseMove" data-move="Flamethrower">Flamethrower</button></body></html>'}));
await page.goto('https://play.pokemonshowdown.com/battle-gen9randombattle-1');
await page.addStyleTag({content:readFileSync('dist/content.css','utf8')});
await page.addScriptTag({content:readFileSync('dist/content.js','utf8')});
const send=async(room,line)=>page.evaluate(({room,line})=>document.dispatchEvent(new CustomEvent('ps-ext-line',{detail:{room,line}})),{room,line});
const request='|request|'+JSON.stringify({side:{id:'p1',pokemon:[{details:'Charizard, L80',condition:'200/200',active:true,baseAbility:'blaze',item:'',moves:['flamethrower']}]}});
await send('battle-gen9randombattle-1',request);
await send('battle-gen9randombattle-1','|switch|p2a: Deer|Sawsbuck-Winter, L80|100/100');
await page.getByText(/possible moves · none seen/).click();
const row=page.locator('.ps-threat summary').filter({hasText:'Double-Edge'}).locator('strong');
const before=await row.textContent();
await send('battle-gen9randombattle-1','|-boost|p2a: Deer|atk|2');
await expect(row).not.toHaveText(before);
const boosted=await row.textContent();
await expect(page.locator('.ps-boosts')).toContainText('+2 Atk');
await send('battle-gen9randombattle-1',request);
await expect(row).toHaveText(boosted);
await send('battle-gen9randombattle-2',request);
await send('battle-gen9randombattle-2','|switch|p2a: Other|Blissey, L80|100/100');
await expect(row).toHaveText(boosted);
await page.evaluate(()=>history.pushState({},'','/battle-gen9randombattle-2'));
await expect(page.getByRole('button',{name:/Battle notes/})).toContainText('Blissey');
await page.evaluate(()=>history.pushState({},'','/battle-gen9randombattle-1'));
await expect(page.locator('.ps-boosts')).toContainText('+2 Atk');
await page.getByRole('button',{name:'Flamethrower',exact:true}).focus();
await expect(page.getByRole('tooltip')).toBeVisible();
await page.keyboard.press('Escape');
await expect(page.getByRole('tooltip')).toHaveCount(0);
await page.evaluate(()=>history.pushState({},'','/'));
await expect(page.locator('.ps-board')).toHaveCount(0);
assert.deepEqual(errors,[]);
await browser.close();
console.log(`Built extension integration passed: possible Double-Edge ${before} → ${boosted} at +2 Atk, request persistence, two-room isolation, keyboard tooltip, and lobby cleanup.`);
